// Dil Değiştirme Fonksiyonu
function setLanguage(lang) {
    if (!i18n[lang]) return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (i18n[lang][key]) {
            el.innerHTML = i18n[lang][key];
        }
    });

    document.documentElement.lang = lang;

    // Buton aktiflik durumlarını güncelle
    const btnEn = document.getElementById('btn-en');
    const btnTr = document.getElementById('btn-tr');

    if (lang === 'en') {
        btnEn.classList.add('active');
        btnTr.classList.remove('active');
    } else {
        btnTr.classList.add('active');
        btnEn.classList.remove('active');
    }

    try {
        localStorage.setItem('preferred_language', lang);
    } catch (e) {
        // localStorage erişimi yoksa yoksay
    }
}

// Sayfa Kaydırmasını Daha Pürüzsüz & Akıcı Yapan Fonksiyon
function initSmoothScroll() {
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function(e) {
            const targetId = this.getAttribute('href');
            if (targetId === '#' || targetId === '') return;
            const targetElement = document.querySelector(targetId);
            if (targetElement) {
                e.preventDefault();
                const header = document.querySelector('.header');
                const headerHeight = header ? header.offsetHeight : 65;
                const elementPosition = targetElement.getBoundingClientRect().top;
                const offsetPosition = elementPosition + window.pageYOffset - (headerHeight + 20);

                window.scrollTo({
                    top: offsetPosition,
                    behavior: 'smooth'
                });
            }
        });
    });
}

// Sayfa Kaydırıldıkça Navbar'ı Kısaltan & Menü Linklerini Güncelleyen Fonksiyon
function initHeaderScrollWatcher() {
    const header = document.querySelector('.header');
    const projelerSection = document.getElementById('projeler');
    const navLinks = document.querySelectorAll('.nav-links a');

    if (!header || !projelerSection) return;

    let ticking = false;

    function handleScroll() {
        const headerHeight = header.offsetHeight || 65;
        const rect = projelerSection.getBoundingClientRect();

        // Projeler alanına yaklaşıldığında veya sayfada aşağı inildiğinde navbar kısalır (compact dock)
        const shouldCompact = (rect.top <= headerHeight + 60) || (window.scrollY > 150);

        if (shouldCompact) {
            if (!header.classList.contains('scrolled-compact')) {
                header.classList.add('scrolled-compact');
            }
        } else {
            if (header.classList.contains('scrolled-compact')) {
                header.classList.remove('scrolled-compact');
            }
        }

        // Aktif menü linki takibi
        const isInProjects = (rect.top <= 160 && rect.bottom >= 160);
        if (isInProjects) {
            navLinks.forEach(link => {
                if (link.getAttribute('href') === '#projeler') {
                    link.classList.add('active');
                } else if (link.getAttribute('href') === '#anasayfa') {
                    link.classList.remove('active');
                }
            });
        } else if (window.scrollY < 200) {
            navLinks.forEach(link => {
                if (link.getAttribute('href') === '#anasayfa') {
                    link.classList.add('active');
                } else if (link.getAttribute('href') === '#projeler') {
                    link.classList.remove('active');
                }
            });
        }
        ticking = false;
    }

    window.addEventListener('scroll', () => {
        if (!ticking) {
            window.requestAnimationFrame(handleScroll);
            ticking = true;
        }
    }, { passive: true });

    window.addEventListener('resize', handleScroll, { passive: true });
    handleScroll();
}

// Buton Olay Dinleyicileri
document.addEventListener('DOMContentLoaded', () => {
    initSmoothScroll();
    initHeaderScrollWatcher();

    const btnEn = document.getElementById('btn-en');
    const btnTr = document.getElementById('btn-tr');

    if (btnEn) {
        btnEn.addEventListener('click', () => setLanguage('en'));
    }
    if (btnTr) {
        btnTr.addEventListener('click', () => setLanguage('tr'));
    }

    // Menü Linkleri Aktiflik Değişimi
    const navLinks = document.querySelectorAll('.nav-links a');
    navLinks.forEach(link => {
        link.addEventListener('click', () => {
            navLinks.forEach(l => l.classList.remove('active'));
            link.classList.add('active');
        });
    });

    // Kayıtlı dil tercihi varsa uygula
    try {
        const savedLang = localStorage.getItem('preferred_language');
        if (savedLang) {
            setLanguage(savedLang);
        }
    } catch (e) {}
});
